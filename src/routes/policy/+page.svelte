    <h1>Tool Policy</h1>
    <p class="legal-updated">Last updated: October 5, 2026</p>
    <h2>Registration</h2>
    <p>A tool is discoverable only when its repository owner is trusted, the repository opts in with the configured topic, and its root manifest passes validation.</p>
    <h2>Routing</h2>
    <p>Catalog metadata does not automatically grant proxy or deployment privileges. Routing remains controlled by the Open Tools host.</p>
    <h2>Behavior</h2>
    <p>Tools should clearly disclose network use, uploads, destructive operations, or external processing. Local processing is preferred when practical.</p>
    <h2>Removal</h2>
    <p>A tool may be removed from the registry if it becomes unsafe, misleading, unavailable, or no longer satisfies the manifest contract.</p>
